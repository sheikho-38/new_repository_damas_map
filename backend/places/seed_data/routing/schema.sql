CREATE TABLE public.routing_boarding_points (
    id bigint NOT NULL,
    bus_route_id bigint NOT NULL,
    bus_node_id bigint NOT NULL,
    sequence_index integer NOT NULL,
    distance_along_route_m double precision NOT NULL,
    geom public.geometry(Point,4326) NOT NULL,
    is_active boolean DEFAULT true NOT NULL,
    CONSTRAINT routing_boarding_points_distance_along_route_m_check CHECK ((distance_along_route_m >= (0)::double precision)),
    CONSTRAINT routing_boarding_points_sequence_index_check CHECK ((sequence_index >= 0))
);
ALTER TABLE public.routing_boarding_points ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.routing_boarding_points_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
CREATE TABLE public.routing_car_states (
    id bigint NOT NULL,
    edge_id bigint NOT NULL,
    direction character varying(7) NOT NULL,
    context_id integer NOT NULL,
    source_node bigint NOT NULL,
    target_node bigint NOT NULL,
    is_initial boolean NOT NULL
);
CREATE TABLE public.routing_car_transitions (
    id bigint NOT NULL,
    source bigint NOT NULL,
    target bigint NOT NULL,
    edge_id bigint NOT NULL,
    direction character varying(7) NOT NULL,
    cost double precision NOT NULL,
    CONSTRAINT routing_car_transitions_cost_check CHECK ((cost >= (0)::double precision))
);
CREATE TABLE public.routing_edges (
    id bigint NOT NULL,
    source bigint NOT NULL,
    target bigint NOT NULL,
    edge_type character varying(16) NOT NULL,
    bus_route_id bigint,
    length_m double precision NOT NULL,
    cost double precision NOT NULL,
    reverse_cost double precision NOT NULL,
    geom public.geometry(LineString,4326) NOT NULL,
    attributes jsonb DEFAULT '{}'::jsonb NOT NULL,
    CONSTRAINT routing_edges_cost_check CHECK ((cost >= (0)::double precision)),
    CONSTRAINT routing_edges_edge_type_check CHECK (((edge_type)::text = ANY ((ARRAY['walk'::character varying, 'car'::character varying, 'bus'::character varying, 'transfer'::character varying, 'board'::character varying, 'alight'::character varying])::text[]))),
    CONSTRAINT routing_edges_length_m_check CHECK ((length_m >= (0)::double precision)),
    CONSTRAINT routing_edges_reverse_cost_check CHECK (((reverse_cost = ('-1'::integer)::double precision) OR (reverse_cost >= (0)::double precision)))
);
ALTER TABLE public.routing_edges ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.routing_edges_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
CREATE TABLE public.routing_nodes (
    id bigint NOT NULL,
    node_type character varying(16) DEFAULT 'road'::character varying NOT NULL,
    geom public.geometry(Point,4326) NOT NULL,
    CONSTRAINT routing_nodes_node_type_check CHECK (((node_type)::text = ANY ((ARRAY['road'::character varying, 'bus'::character varying])::text[])))
);
ALTER TABLE public.routing_nodes ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.routing_nodes_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
CREATE TABLE public.routing_turn_restrictions (
    id bigint NOT NULL,
    osm_relation_id bigint NOT NULL,
    restriction_type character varying(32) NOT NULL,
    mode character varying(8) NOT NULL,
    sequence_index integer NOT NULL,
    directed_path jsonb NOT NULL,
    CONSTRAINT routing_turn_restrictions_mode_check CHECK (((mode)::text = 'car'::text)),
    CONSTRAINT routing_turn_restrictions_sequence_index_check CHECK ((sequence_index > 0))
);
ALTER TABLE public.routing_turn_restrictions ALTER COLUMN id ADD GENERATED ALWAYS AS IDENTITY (
    SEQUENCE NAME public.routing_turn_restrictions_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
